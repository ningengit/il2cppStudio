namespace Il2CppStudio.Core.Workspace;

/// <summary>
/// Makes an exported assembly folder a buildable C# project: <c>&lt;Asm&gt;.csproj</c> referencing the sibling exported
/// stub DLLs (dependencies) and the Unity BCL (mscorlib/System/System.Core from the editor's unityaot profile),
/// plus <c>Il2CppStudio.Native.cs</c>, the shim that defines the <c>NativeIntrinsics</c> escape hatches so even
/// partially lifted bodies compile. Offline-only: no NuGet packages, implicit framework references disabled.
/// </summary>
public static class ProjectFileWriter
{
    public static string Write(string assemblyDir, string assemblyName, IEnumerable<string> referencePaths)
    {
        var refs = string.Join(Environment.NewLine, referencePaths.Distinct(StringComparer.OrdinalIgnoreCase).Select(p =>
            $"    <Reference Include=\"{Path.GetFileNameWithoutExtension(p)}\"><HintPath>{p}</HintPath><Private>false</Private></Reference>"));
        var csproj = $"""
            <Project Sdk="Microsoft.NET.Sdk">
              <!-- Generated by Il2CppStudio: compiles the reconstructed C# of {assemblyName} against the exported stubs. -->
              <PropertyGroup>
                <TargetFramework>netstandard2.1</TargetFramework>
                <AssemblyName>{assemblyName}</AssemblyName>
                <DisableImplicitFrameworkReferences>true</DisableImplicitFrameworkReferences>
                <NoStdLib>true</NoStdLib>
                <NoConfig>true</NoConfig>
                <LangVersion>latest</LangVersion>
                <ImplicitUsings>disable</ImplicitUsings>
                <Nullable>disable</Nullable>
                <AllowUnsafeBlocks>true</AllowUnsafeBlocks>
                <GenerateAssemblyInfo>false</GenerateAssemblyInfo>
                <EnableDefaultCompileItems>false</EnableDefaultCompileItems>
                <NoWarn>$(NoWarn);CS0108;CS0114;CS0162;CS0168;CS0169;CS0219;CS0414;CS0649;CS1998</NoWarn>
              </PropertyGroup>
              <ItemGroup>
                <Compile Include="csharp/**/*.cs" />
                <Compile Include="Il2CppStudio.Native.cs" />
              </ItemGroup>
              <ItemGroup>
            {refs}
              </ItemGroup>
            </Project>
            """;
        var path = Path.Combine(assemblyDir, assemblyName + ".csproj");
        File.WriteAllText(path, csproj);
        File.WriteAllText(Path.Combine(assemblyDir, "Il2CppStudio.Native.cs"), NativeShim);
        return path;
    }

    /// <summary>Source twin of the stub modules' NativeIntrinsics type (same names and signatures).</summary>
    public const string NativeShim = """
        // Generated by Il2CppStudio. Escape hatches used where native code had no exact C# equivalent; every use is
        // listed with its RVA in <Assembly>_Error_Logs.txt. They throw at runtime: the code compiles, it is not executable.
        namespace Il2CppStudio.Native
        {
            internal static class NativeIntrinsics
            {
                public static long Asm(string instruction) => throw new System.NotSupportedException(instruction);
                public static void Stmt(string instruction) => throw new System.NotSupportedException(instruction);
                public static long CallNative(string function, long a0, long a1, long a2, long a3) => throw new System.NotSupportedException(function);
                public static T Reinterpret<T>(object value) => throw new System.NotSupportedException("reinterpret");
            }
        }
        """;
}
